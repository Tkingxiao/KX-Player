// ── AI ──────────────────────────────────────────────────────

export interface ChatMessage {
  role: string
  content: string
}

export interface AiChatPayload {
  baseUrl: string
  apiKey: string
  model: string
  /** `ai_ping` 不需要它（Rust 侧 `#[serde(default)]`），由后端补一条最小请求 */
  messages?: ChatMessage[]
  temperature?: number
}

export interface AiChatResult {
  ok: boolean
  content: string
  error?: string
}

export interface AiPingResult {
  ok: boolean
  message: string
  /** 以下三项由 AI-5 的连通性测试回显；失败时 Rust 侧整键缺席（camelCase，见 model.rs） */
  model?: string
  latencyMs?: number
  totalTokens?: number
}

export interface AiModelsResult {
  ok: boolean
  models: string[]
  error?: string
}
