/**
 * 契约层 · DTO：Rust 侧 `#[serde(rename_all = "camelCase")]` 结构体的 TS 镜像。
 *
 * 结构体名与 TS 名不同处（历史遗留，改名要动 20+ 个引用文件，收益不抵成本）：
 * `DirEntryInfo → DirEntry`、`PlayerState → MpvPlayerState`。
 * 命令名与参数键名由 `npm run check:ipc` 校验；**字段级**一致性靠这里的注释对照。
 */

// ── 曲库 ────────────────────────────────────────────────────

export interface Track {
  id: string
  name: string
  path: string
  duration: number
  artist: string
  album: string
  format: string
  isVideo: boolean
  coverPath: string | null
  coverData: string | null
  lyricsPath: string | null
  fileMtime: number
  fileSize: number
  metaTitle: string | null
  metaArtist: string | null
  genre: string | null
  bitrate: number | null
  sampleRate: number | null
  loudnessLufs?: number | null
  albumCoverData?: string | null
}

export interface FolderNode {
  name: string
  path: string
  children: FolderNode[]
  tracks: Track[]
  trackCount: number
  coverData: string | null
}

export interface ScanResult {
  folderPaths: string[]
  artists: unknown[]
  folderTree: FolderNode[]
  allTracks: Track[]
  fileCount: number
}

/** Rust: `commands::dialog_fs::DirEntryInfo` */
export interface DirEntry {
  name: string
  isFile: boolean
  isDirectory: boolean
}

export interface PlayProgress {
  trackId: string
  positionMs: number
  completed: boolean
  playCount: number
  playedAt: number
  lastSpeed: number | null
}

export interface Bookmark {
  id: string
  trackId: string
  atMs: number
  label: string
  createdAt: number
}

export interface FavItem {
  id: string
  name: string
  trackIds: string[]
  isDefault?: boolean
  cover?: string
}

